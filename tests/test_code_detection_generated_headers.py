# region [02] Incremental cache signature


def _snapshot(path: Path) -> FileSnapshot:
    observed = path.stat()
    return FileSnapshot(
        str(path),
        observed.st_dev,
        observed.st_ino,
        observed.st_size,
        observed.st_mtime_ns,
        getattr(observed, "st_birthtime_ns", observed.st_ctime_ns),
    )


class _Inventory:
    def __init__(self, paths: Iterable[Path]):
        self.paths = tuple(paths)

    def snapshots(self, _scan_id: int) -> Iterator[FileSnapshot]:
        return iter(_snapshot(path) for path in self.paths)


class _FrameworkState:
    def begin_route_phase(
        self,
        _run_id: int,
        _route: str,
        _phase: str,
        *,
        source_run_id: int | None = None,
    ) -> None:
        del source_run_id

    def complete_route_phase(
        self,
        _run_id: int,
        _route: str,
        _phase: str,
        summary: Mapping[str, object] | None = None,
    ) -> None:
        assert summary is not None

    def fail_route_phase(
        self,
        _run_id: int,
        _route: str,
        _phase: str,
        _exc: BaseException,
    ) -> None:
        raise AssertionError("detector cache fixture route must not fail")


def test_detector_version_change_invalidates_the_incremental_cache(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    source = tmp_path / "client.py"
    source.write_text("def ready():\n    return True\n", encoding="utf-8")
    config = CodeRouteConfig(
        state_path=tmp_path / "state" / "code.sqlite3",
        dedup_path=tmp_path / "state" / "dedup.sqlite3",
    )
    inventory = _Inventory((source,))
    framework = _FrameworkState()

    first = CodeRoute(config, inventory, framework, 1, 1).run()
    cached = CodeRoute(config, inventory, framework, 2, 2).run()

    assert first.processed == 1
    assert cached.processed == 0
    assert cached.cache_hits == 1
    assert f"artifact-detector={DETECTOR_VERSION}" in first.processing_signature

    monkeypatch.setattr(
        code_route_module,
        "DETECTOR_VERSION",
        "code-artifact-detector-regression",
    )
    changed = CodeRoute(config, inventory, framework, 3, 3).run()

    assert changed.processing_signature != first.processing_signature
    assert changed.processed == 1
    assert changed.cache_hits == 0


