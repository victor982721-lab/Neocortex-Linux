# region [01] Generated-header classification


@pytest.mark.parametrize(  # type: ignore[untyped-decorator]
    ("path", "text", "style"),
    (
        (
            Path("src/client.py"),
            "# Copyright 2026\n# This file is auto-generated. Do not edit.\nvalue = 1\n",
            "hash",
        ),
        (
            Path("src/client.ts"),
            "// Code generated by schema-tool. DO NOT EDIT.\nexport const value = 1;\n",
            "slash",
        ),
        (
            Path("src/client.go"),
            "// WARNING: This file is machine generated.\npackage client\n",
            "slash",
        ),
        (
            Path("src/client.cs"),
            "/*\n * <auto-generated />\n */\ninternal sealed class Client {}\n",
            "c-block",
        ),
        (
            Path("src/client.xml"),
            '<?xml version="1.0"?>\n<!-- This file was automatically generated. -->\n<client />\n',
            "xml-block",
        ),
        (
            Path("src/client.ps1"),
            "<#\n@generated\n#>\nWrite-Output 'ready'\n",
            "powershell-block",
        ),
    ),
)
def test_semantic_header_comments_mark_generated_artifacts(
    path: Path,
    text: str,
    style: str,
) -> None:
    classification = classify_artifact(path, text)

    assert classification.artifact_kind is ArtifactKind.GENERATED
    assert classification.generated is True
    assert "header:generated-marker" in classification.evidence
    assert f"detector:{DETECTOR_VERSION}" in classification.evidence
    assert any(
        item.startswith(f"header:generated-marker:{style}:line-")
        for item in classification.evidence
    )


@pytest.mark.parametrize(  # type: ignore[untyped-decorator]
    ("path", "text"),
    (
        (
            Path("src/rules.py"),
            "import re\nMARKER = re.compile(r'do not edit|generated file|@generated')\n",
        ),
        (
            Path("src/rules.py"),
            '"""Generated file markers recognized by this detector."""\nvalue = 1\n',
        ),
        (
            Path("src/rules.py"),
            "# Detector recognizes generated file declarations.\nvalue = 1\n",
        ),
        (
            Path("src/rules.py"),
            "value = 1\n# This file is generated.\n",
        ),
        (
            Path("src/rules.ts"),
            'const marker = "// generated file";\nexport { marker };\n',
        ),
        (
            Path("src/rules.json"),
            '{"notice": "do not edit", "kind": "generated file"}\n',
        ),
    ),
)
def test_rule_literals_and_non_header_text_are_not_generated(
    path: Path,
    text: str,
) -> None:
    classification = classify_artifact(path, text)

    assert classification.artifact_kind is not ArtifactKind.GENERATED
    assert classification.generated is False
    assert "header:generated-marker" not in classification.evidence


def test_detector_does_not_classify_its_own_rule_literals_as_generated() -> None:
    module_file = code_detection.__file__
    assert module_file is not None
    detector_path = Path(module_file).resolve()

    classification = classify_artifact(
        detector_path,
        detector_path.read_text(encoding="utf-8"),
    )

    assert classification.artifact_kind is ArtifactKind.SOURCE
    assert classification.generated is False
    assert "header:generated-marker" not in classification.evidence


def test_generated_path_role_remains_supported_without_a_header() -> None:
    classification = classify_artifact(
        Path("src/build/client.py"),
        "value = 1\n",
    )

    assert classification.artifact_kind is ArtifactKind.GENERATED
    assert classification.generated is True
    assert "path:generated:build" in classification.evidence
    assert "header:generated-marker" not in classification.evidence


